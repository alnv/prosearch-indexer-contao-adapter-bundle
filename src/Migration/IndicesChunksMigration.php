<?php

declare(strict_types=1);

namespace Alnv\ProSearchIndexerContaoAdapterBundle\Migration;

use Alnv\ProSearchIndexerContaoAdapterBundle\Helpers\States;
use Alnv\ProSearchIndexerContaoAdapterBundle\Indexing\Extraction\TextNormalizer;
use Alnv\ProSearchIndexerContaoAdapterBundle\Indexing\IndexDocument;
use Alnv\ProSearchIndexerContaoAdapterBundle\Indexing\IndicesRepository;
use Alnv\ProSearchIndexerContaoAdapterBundle\Indexing\SyncStatus;
use Contao\CoreBundle\Migration\AbstractMigration;
use Contao\CoreBundle\Migration\MigrationResult;
use Doctrine\DBAL\Connection;

class IndicesChunksMigration extends AbstractMigration
{
    private const string T = IndicesRepository::TABLE;
    private const string C = IndicesRepository::CHUNK_TABLE;

    /**
     * Column definitions as generated by Contao from the DCA ("contao:migrate --dry-run").
     */
    public const array COLUMNS = [
        'text' => 'MEDIUMTEXT DEFAULT NULL',
        'strong' => 'BLOB DEFAULT NULL',
        'headings' => 'BLOB DEFAULT NULL',
        'url_hash' => "CHAR(40) DEFAULT '' NOT NULL",
        'rootId' => 'INT UNSIGNED DEFAULT 0 NOT NULL',
        'content_hash' => "CHAR(64) DEFAULT '' NOT NULL",
        'checksum' => "CHAR(64) DEFAULT '' NOT NULL",
        'source_hash' => "VARCHAR(64) DEFAULT '' NOT NULL",
        'chunk_count' => 'INT UNSIGNED DEFAULT 0 NOT NULL',
        'revision' => 'INT UNSIGNED DEFAULT 0 NOT NULL',
        'synced_revision' => 'INT UNSIGNED DEFAULT 0 NOT NULL',
        'sync_status' => "VARCHAR(16) DEFAULT 'pending' NOT NULL",
        'sync_attempts' => 'SMALLINT UNSIGNED DEFAULT 0 NOT NULL',
        'sync_error' => 'TEXT DEFAULT NULL',
        'sync_next_at' => 'INT UNSIGNED DEFAULT 0 NOT NULL',
        'sync_claim' => "VARCHAR(32) DEFAULT '' NOT NULL",
        'sync_claimed_until' => 'INT UNSIGNED DEFAULT 0 NOT NULL',
        'synced_index' => "VARCHAR(255) DEFAULT '' NOT NULL",
    ];

    public const array INDEXES = [
        'url_hash' => 'url_hash',
        'sync_status_sync_next_at' => 'sync_status, sync_next_at',
        'sync_claim' => 'sync_claim',
    ];

    public const string CHUNK_TABLE_SQL = "CREATE TABLE tl_indices_chunks (id INT UNSIGNED AUTO_INCREMENT NOT NULL, pid INT UNSIGNED DEFAULT 0 NOT NULL, tstamp INT UNSIGNED DEFAULT 0 NOT NULL, sorting INT UNSIGNED DEFAULT 0 NOT NULL, text MEDIUMTEXT DEFAULT NULL, token_count INT UNSIGNED DEFAULT 0 NOT NULL, start_offset INT UNSIGNED DEFAULT 0 NOT NULL, end_offset INT UNSIGNED DEFAULT 0 NOT NULL, hash CHAR(64) DEFAULT '' NOT NULL, UNIQUE INDEX pid_sorting (pid, sorting), PRIMARY KEY (id)) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci ENGINE = InnoDB";

    private const int BATCH = 100;

    public function __construct(
        private readonly Connection        $connection,
        private readonly IndicesRepository $repository,
    )
    {
    }

    public function getName(): string
    {
        return 'ProSearch 4.0: tl_indices.document => text and tl_indices_chunks';
    }

    public function shouldRun(): bool
    {
        $schemaManager = $this->connection->createSchemaManager();

        if (!$schemaManager->tablesExist([self::T])) {
            return false;
        }

        $columns = $this->columns();

        if (array_diff(array_map('strtolower', array_keys(self::COLUMNS)), $columns) || !$schemaManager->tablesExist([self::C])) {
            return true;
        }

        if (\in_array('document', $columns, true)) {
            return true;
        }

        return (bool)$this->connection->fetchOne("SELECT 1 FROM " . self::T . " WHERE url_hash='' AND url IS NOT NULL AND url<>'' LIMIT 1")
            || (bool)$this->connection->fetchOne("SELECT 1 FROM " . self::T . " WHERE state=? AND chunk_count=0 AND text IS NOT NULL AND text<>'' LIMIT 1", [States::ACTIVE]);
    }

    public function run(): MigrationResult
    {
        $start = microtime(true);
        $this->addSchema();

        $this->connection->executeStatement("UPDATE " . self::T . " SET url_hash=SHA1(url) WHERE url_hash='' AND url IS NOT NULL AND url<>''");
        $roots = $this->fillRootIds();

        [$converted, $unreadable] = \in_array('document', $this->columns(), true) ? $this->convertDocuments() : [0, []];
        $chunks = $this->createMissingChunks();

        $messages = [\sprintf('%d records converted, %d chunks created, root page set for %d records.', $converted, $chunks, $roots)];

        if (\in_array('document', $this->columns(), true)) {
            $remaining = (int)$this->connection->fetchOne('SELECT COUNT(*) FROM ' . self::T . ' WHERE text IS NULL');

            if (0 === $remaining) {
                $this->connection->executeStatement('ALTER TABLE ' . self::T . ' DROP document');
                $messages[] = 'Column "document" removed.';
            } else {
                $messages[] = \sprintf('Column "document" kept: %d records could not be converted (IDs %s). Fix or delete them and run the migration again.', $remaining, implode(', ', \array_slice($unreadable, 0, 20)));

                return $this->createResult(false, implode(' ', $messages));
            }
        }

        $messages[] = \sprintf('(%.1f s) The documents are transferred by the queue (cron job or "prosearch:index:sync").', microtime(true) - $start);

        return $this->createResult(true, implode(' ', $messages));
    }

    private function addSchema(): void
    {
        $columns = $this->columns();
        $add = [];

        foreach (self::COLUMNS as $name => $definition) {
            if (!\in_array(strtolower($name), $columns, true)) {
                $add[] = 'ADD ' . $this->connection->quoteIdentifier($name) . ' ' . $definition;
            }
        }

        if ([] !== $add) {
            $this->connection->executeStatement('ALTER TABLE ' . self::T . ' ' . implode(', ', $add));
        }

        $indexes = array_map('strtolower', array_keys($this->connection->createSchemaManager()->listTableIndexes(self::T)));

        foreach (self::INDEXES as $name => $indexColumns) {
            if (!\in_array($name, $indexes, true)) {
                $this->connection->executeStatement('CREATE INDEX ' . $name . ' ON ' . self::T . ' (' . $indexColumns . ')');
            }
        }

        if (!$this->connection->createSchemaManager()->tablesExist([self::C])) {
            $this->connection->executeStatement(self::CHUNK_TABLE_SQL);
        }
    }

    /**
     * Root page of every record (used for the index name, formerly resolved per document).
     */
    private function fillRootIds(): int
    {
        $updated = 0;
        $pageIds = $this->connection->fetchFirstColumn('SELECT DISTINCT pageId FROM ' . self::T . ' WHERE rootId=0 AND pageId>0');

        if ([] === $pageIds || !$this->connection->createSchemaManager()->tablesExist(['tl_page'])) {
            return 0;
        }

        foreach ($pageIds as $pageId) {
            $root = $this->rootOf((int)$pageId);

            if ($root > 0) {
                $updated += $this->connection->executeStatement('UPDATE ' . self::T . ' SET rootId=? WHERE pageId=? AND rootId=0', [$root, (int)$pageId]);
            }
        }

        return $updated;
    }

    private function rootOf(int $pageId): int
    {
        for ($i = 0; $i < 50 && $pageId > 0; ++$i) {
            $page = $this->connection->fetchAssociative('SELECT id, pid, type FROM tl_page WHERE id=?', [$pageId]);

            if (!$page) {
                return 0;
            }

            if ('root' === $page['type']) {
                return (int)$page['id'];
            }

            $pageId = (int)$page['pid'];
        }

        return 0;
    }

    /**
     * @return array{0: int, 1: list<int>} converted records, IDs that could not be read
     */
    private function convertDocuments(): array
    {
        $converted = 0;
        $unreadable = [];
        $lastId = 0;
        $chunker = $this->repository->getChunker();

        do {
            $rows = $this->connection->fetchAllAssociative(
                'SELECT id, state, doc_type, document FROM ' . self::T . ' WHERE text IS NULL AND id>? ORDER BY id LIMIT ' . self::BATCH,
                [$lastId],
            );

            $this->connection->transactional(function (Connection $connection) use ($rows, $chunker, &$converted, &$unreadable): void {
                foreach ($rows as $row) {
                    $content = self::convert($row['document'], (string)$row['doc_type']);

                    if (null === $content) {
                        $unreadable[] = (int)$row['id'];

                        continue;
                    }

                    $chunks = States::ACTIVE === $row['state'] && '' !== $content['text'] ? iterator_to_array($chunker->chunk($content['text']), false) : [];

                    $connection->executeStatement(
                        "UPDATE " . self::T . " SET text=?, strong=?, headings=?, content_hash=?, checksum='', chunk_count=?, revision=revision+1, sync_status=?, sync_attempts=0, sync_error='', sync_next_at=0 WHERE id=?",
                        [$content['text'], serialize($content['strong']), serialize($content['headings']), hash('sha256', $content['text']), \count($chunks), SyncStatus::PENDING, (int)$row['id']],
                    );

                    $this->repository->replaceChunks($connection, (int)$row['id'], $chunks);
                    ++$converted;
                }
            });

            $lastId = [] !== $rows ? (int)end($rows)['id'] : $lastId;
        } while (\count($rows) === self::BATCH);

        return [$converted, $unreadable];
    }

    private function createMissingChunks(): int
    {
        $created = 0;
        $lastId = 0;
        $chunker = $this->repository->getChunker();

        do {
            $rows = $this->connection->fetchAllAssociative(
                "SELECT id, text FROM " . self::T . " WHERE state=? AND chunk_count=0 AND text IS NOT NULL AND text<>'' AND id>? ORDER BY id LIMIT " . self::BATCH,
                [States::ACTIVE, $lastId],
            );

            $this->connection->transactional(function (Connection $connection) use ($rows, $chunker, &$created): void {
                foreach ($rows as $row) {
                    $chunks = iterator_to_array($chunker->chunk((string)$row['text']), false);
                    $this->repository->replaceChunks($connection, (int)$row['id'], $chunks);

                    // a text without a single token (only invisible characters) is emptied, otherwise
                    // the record would be selected by every following run
                    $connection->executeStatement(
                        'UPDATE ' . self::T . ' SET chunk_count=?, revision=revision+1, sync_status=?, sync_next_at=0' . ([] === $chunks ? ", text=''" : '') . ' WHERE id=?',
                        [\count($chunks), SyncStatus::PENDING, (int)$row['id']],
                    );
                    $created += \count($chunks);
                }
            });

            $lastId = [] !== $rows ? (int)end($rows)['id'] : $lastId;
        } while (\count($rows) === self::BATCH);

        return $created;
    }

    /**
     * Converts the serialized 3.x document into the new structure.
     *
     * @return array{text: string, strong: list<string>, headings: array<string, list<string>>}|null null if not readable
     */
    public static function convert(mixed $document, string $docType): ?array
    {
        $headings = IndexDocument::emptyHeadings();

        if (null === $document || '' === $document) {
            return ['text' => '', 'strong' => [], 'headings' => $headings];
        }

        $data = \is_string($document) ? @unserialize($document, ['allowed_classes' => false]) : false;

        if (!\is_array($data)) {
            return null;
        }

        // "document" was a binary column: texts of old PDF imports may contain invalid UTF-8
        $list = static function (mixed $value): array {
            $values = \is_array($value) ? $value : [$value];
            $values = array_map(static fn($v): string => \is_scalar($v) ? trim(TextNormalizer::toUtf8((string)$v)) : '', $values);

            return array_values(array_unique(array_filter($values, static fn(string $v): bool => '' !== $v)));
        };

        $text = $list($data['text'] ?? []);
        $pdf = $list($data['document'] ?? []);
        $strong = $list($data['strong'] ?? []);

        foreach (array_keys($headings) as $level) {
            $headings[$level] = $list($data[$level] ?? []);
        }

        if (IndexDocument::TYPE_FILE === $docType) {
            // PDF: link/meta texts become highlighted texts, the PDF text layer is the document text
            return ['text' => implode("\n", $pdf), 'strong' => array_values(array_unique([...$strong, ...$text])), 'headings' => $headings];
        }

        return ['text' => implode("\n", [...$text, ...$pdf]), 'strong' => $strong, 'headings' => $headings];
    }

    /**
     * @return list<string> lower case column names of tl_indices
     */
    private function columns(): array
    {
        return array_map('strtolower', array_keys($this->connection->createSchemaManager()->listTableColumns(self::T)));
    }
}
